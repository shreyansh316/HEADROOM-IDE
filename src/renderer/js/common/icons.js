export function getFileIcon(fileName = '') {
    const ext = (fileName.split('.').pop() || '').toLowerCase();
    switch (ext) {
        case 'js':
        case 'mjs':
        case 'cjs':
        case 'jsx':
        case 'json':
        case 'html':
        case 'css':
        case 'py':
        case 'sh':
            return ICONS.fileCode;
        case 'md':
        case 'markdown':
        case 'txt':
        case 'log':
            return ICONS.fileDoc;
        default:
            return ICONS.fileDefault;
    }
}
